    public void menuHistoricoCobranca() {
        boolean continuar = true;
        while (continuar) {
            ctx.imprimirSeparador("HISTORICO E COBRANCAS");
            System.out.println("  [1] Registrar disciplina cursada");
            System.out.println("  [2] Exibir historico de um aluno");
            System.out.println("  [3] Gerar extrato de cobranca por semestre");
            System.out.println("  [4] Exibir log de notificacoes de cobranca");
            System.out.println("  [0] Voltar");
            int opcao = ctx.lerInt("  Opcao: ");
            System.out.println();
            switch (opcao) {
                case 1  -> registrarDisciplinaCursada();
                case 2  -> exibirHistorico();
                case 3  -> gerarExtratoCobranca();
                case 4  -> exibirLogCobranca();
                case 0  -> continuar = false;
                default -> System.out.println("  [!] Opcao invalida.");
            }
            if (continuar) ctx.pausar();
        }
    }

    private void registrarDisciplinaCursada() {
        ctx.imprimirSeparador("REGISTRAR DISCIPLINA CURSADA");
        System.out.println("  Selecione o aluno:");
        Aluno aluno = ctx.selecionarAluno();
        if (aluno == null) return;
        System.out.println("  Selecione a disciplina:");
        Disciplina disciplina = ctx.selecionarDisciplina();
        if (disciplina == null) return;
        String semestre = ctx.lerLinha("  Semestre (ex: 2026/1): ");
        double nota     = ctx.lerDouble("  Nota final (0-10)    : ");
        System.out.println("  Resultado:");
        System.out.println("    [1] APROVADO");
        System.out.println("    [2] REPROVADO");
        boolean aprovado = ctx.lerInt("  Escolha: ") == 1;
        try {
            new DisciplinaCursada(semestre, aprovado, nota, aluno, disciplina);
            System.out.println("  [OK] Registro adicionado ao historico do aluno.");
        } catch (Exception e) {
            System.out.println("  [ERRO] " + e.getMessage());
        }
    }

    private void exibirHistorico() {
        ctx.imprimirSeparador("HISTORICO ESCOLAR");
        Aluno aluno = ctx.selecionarAluno();
        if (aluno == null) return;
        System.out.printf("  Aluno: %s %s | Matricula: %s%n",
                aluno.getNome(), aluno.getSobrenome(), aluno.getMatricula());
        if (aluno.getHistorico().isEmpty()) {
            System.out.println("  Nenhuma disciplina cursada registrada.");
            return;
        }
        System.out.printf("%n  %-22s %-10s %-6s %s%n", "Disciplina", "Semestre", "Nota", "Situacao");
        System.out.println("  " + "-".repeat(55));
        for (DisciplinaCursada dc : aluno.getHistorico()) {
            System.out.printf("  %-22s %-10s %-6.1f %s%n",
                    dc.getDisciplina().getNome(),
                    dc.getSemestre(),
                    dc.getNotaFinal(),
                    dc.getIsAprovado() ? "APROVADO" : "REPROVADO");
        }
    }

    private void gerarExtratoCobranca() {
        ctx.imprimirSeparador("EXTRATO DE COBRANCA");
        Aluno aluno = ctx.selecionarAluno();
        if (aluno == null) return;
        String semestre = ctx.lerLinha("  Semestre (ex: 2026/2): ");
        java.util.List<Inscricao> inscricoes = ctx.servicoCobranca.gerarCobranca(aluno, semestre);
        System.out.printf("  Aluno: %s %s | Matricula: %s | Semestre: %s%n",
                aluno.getNome(), aluno.getSobrenome(), aluno.getMatricula(), semestre);
        if (inscricoes.isEmpty()) {
            System.out.println("  Nenhuma inscricao ativa para este semestre.");
            return;
        }
        System.out.printf("%n  %-12s %-25s %-12s%n", "Turma", "Disciplina", "Tipo");
        System.out.println("  " + "-".repeat(52));
        for (Inscricao i : inscricoes) {
            System.out.printf("  %-12s %-25s %-12s%n",
                    i.getTurma().getCodigo(),
                    i.getTurma().getDisciplina().getNome(),
                    i.getTipoInscricao());
        }
        System.out.println("  Total de inscricoes cobraveis: " + inscricoes.size());
    }

    private void exibirLogCobranca() {
        ctx.imprimirSeparador("LOG DE NOTIFICACOES DE COBRANCA");
        java.util.List<domain.NotificacaoCobranca> notificacoes = ctx.servicoCobranca.getNotificacoes();
        if (notificacoes.isEmpty()) {
            System.out.println("  Nenhuma notificacao registrada.");
            return;
        }
        System.out.println("  Total: " + notificacoes.size() + " notificacao(oes)\n");
        for (int i = 0; i < notificacoes.size(); i++) {
            System.out.printf("  [%3d] %s%n", i + 1, notificacoes.get(i).toString());
        }
    }
