    public void menuSecretaria() {
        boolean continuar = true;
        while (continuar) {
            ctx.imprimirSeparador("SECRETARIA");
            System.out.println("  [1] Exibir dados da secretaria ativa");
            System.out.println("  [2] Alterar cargo");
            System.out.println("  [3] Alterar email corporativo");
            System.out.println("  [4] Alterar senha");
            System.out.println("  [0] Voltar");
            int opcao = ctx.lerInt("  Opcao: ");
            System.out.println();
            switch (opcao) {
                case 1  -> exibirSecretaria();
                case 2  -> alterarCargo();
                case 3  -> alterarEmailSecretaria();
                case 4  -> alterarSenhaSecretaria();
                case 0  -> continuar = false;
                default -> System.out.println("  [!] Opcao invalida.");
            }
            if (continuar) ctx.pausar();
        }
    }

    private void exibirSecretaria() {
        Secretaria s = ctx.secretariaAtiva;
        System.out.println("  --- Secretaria Ativa ---");
        System.out.println("  Cargo  : " + s.getCargo());
        System.out.println("  Email  : " + s.getEmailCorporativo());
        System.out.println("  End.   : " + s.getEndereco());
        System.out.println("  Alunos cadastrados    : " + s.getAlunos().size());
        System.out.println("  Professores cadastrados: " + s.getProfessores().size());
        System.out.println("  Disciplinas cadastradas: " + s.getDisciplinas().size());
        System.out.println("  Curriculos cadastrados : " + s.getCurriculos().size());
    }

    private void alterarCargo() {
        ctx.imprimirSeparador("ALTERAR CARGO");
        String cargo = ctx.lerLinha("  Novo cargo: ");
        try {
            ctx.secretariaAtiva.setCargo(cargo);
            System.out.println("  [OK] Cargo atualizado.");
        } catch (Exception e) {
            System.out.println("  [ERRO] " + e.getMessage());
        }
    }

    private void alterarEmailSecretaria() {
        ctx.imprimirSeparador("ALTERAR EMAIL");
        String email = ctx.lerLinha("  Novo email: ");
        try {
            if (!ctx.dados.emailDisponivel(email, ctx.secretariaAtiva)) {
                throw new IllegalArgumentException("Email ja cadastrado");
            }
            ctx.secretariaAtiva.setEmailCorporativo(email);
            System.out.println("  [OK] Email atualizado.");
        } catch (Exception e) {
            System.out.println("  [ERRO] " + e.getMessage());
        }
    }

    private void alterarSenhaSecretaria() {
        ctx.imprimirSeparador("ALTERAR SENHA");
        String senhaAtual = ctx.lerLinha("  Senha atual: ");
        String novaSenha  = ctx.lerLinha("  Nova senha : ");
        try {
            ctx.secretariaAtiva.alterarSenha(senhaAtual, novaSenha);
            System.out.println("  [OK] Senha alterada com sucesso.");
        } catch (Exception e) {
            System.out.println("  [ERRO] " + e.getMessage());
        }
    }

