    public void menuDisciplinas() {
        boolean continuar = true;
        while (continuar) {
            ctx.imprimirSeparador("DISCIPLINAS");
            System.out.println("  [1] Cadastrar disciplina");
            System.out.println("  [2] Listar disciplinas");
            System.out.println("  [3] Editar disciplina");
            System.out.println("  [0] Voltar");
            int opcao = ctx.lerInt("  Opcao: ");
            System.out.println();
            switch (opcao) {
                case 1  -> cadastrarDisciplina();
                case 2  -> listarDisciplinas();
                case 3  -> editarDisciplina();
                case 0  -> continuar = false;
                default -> System.out.println("  [!] Opcao invalida.");
            }
            if (continuar) ctx.pausar();
        }
    }

    private void cadastrarDisciplina() {
        ctx.imprimirSeparador("CADASTRAR DISCIPLINA");
        System.out.println("  Selecione o curso:");
        Curso curso = ctx.selecionarCurso();
        if (curso == null) return;
        String nome   = ctx.lerLinha("  Nome da disciplina: ");
        String codigo = ctx.lerLinha("  Codigo            : ");
        int creditos  = ctx.lerInt  ("  Creditos          : ");
        try {
            Disciplina disciplina = new Disciplina(nome, codigo, creditos, curso, ctx.secretariaAtiva);
            ctx.disciplinas.add(disciplina);
            System.out.println("  [OK] Disciplina '" + nome + "' cadastrada.");
        } catch (Exception e) {
            System.out.println("  [ERRO] " + e.getMessage());
        }
    }

    private void listarDisciplinas() {
        ctx.imprimirSeparador("LISTA DE DISCIPLINAS");
        if (ctx.disciplinas.isEmpty()) { System.out.println("  Nenhuma disciplina cadastrada."); return; }
        for (Disciplina d : ctx.disciplinas) {
            System.out.printf("  Nome: %-25s | Cod: %-8s | Creditos: %d | Curso: %s%n",
                    d.getNome(), d.getCodigo(), d.getCreditos(), d.getCurso().getNome());
        }
    }

    private void editarDisciplina() {
        ctx.imprimirSeparador("EDITAR DISCIPLINA");
        Disciplina d = ctx.selecionarDisciplina();
        if (d == null) return;
        System.out.println("  (deixe em branco para manter o valor atual)");
        String nome   = ctx.lerLinha("  Novo nome [" + d.getNome() + "]: ");
        String codigo = ctx.lerLinha("  Novo codigo [" + d.getCodigo() + "]: ");
        String cred   = ctx.lerLinha("  Novos creditos [" + d.getCreditos() + "]: ");
        try {
            if (!nome.isBlank())   d.setNome(nome);
            if (!codigo.isBlank()) d.setCodigo(codigo);
            if (!cred.isBlank())   d.setCreditos(Integer.parseInt(cred));
            System.out.println("  [OK] Disciplina atualizada.");
        } catch (Exception e) {
            System.out.println("  [ERRO] " + e.getMessage());
        }
    }

